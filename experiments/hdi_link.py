"""Do oil-price swings show up in human development? UNDP HDI (annual) against Brent.

HDI moves slowly (life expectancy, schooling, income per head), so the test is annual: the change in
HDI on the current and previous year's log change in the average Brent price, pooled over a group
of countries with country fixed effects (each country's own average HDI growth), Newey-West
errors over years. Oil importers and Gulf exporters are fitted separately; 2020 (COVID) is
reported with and without.

    uv run experiments/hdi_link.py   # writes notes/hdi-link.md
"""

from __future__ import annotations

import sys
from datetime import UTC, datetime

import numpy as np
import pandas as pd

import macro_data as md

HDI_URL = "https://hdr.undp.org/sites/default/files/2023-24_HDR/HDR23-24_Composite_indices_complete_time_series.csv"
OUT = md.ROOT / "notes" / "hdi-link.md"
GROUPS = {"Oil importers": ["USA", "GBR", "DEU", "FRA", "ITA", "ESP", "JPN", "IND"],
          "Gulf exporters": ["SAU", "ARE", "KWT", "QAT", "IRQ", "IRN", "OMN", "BHR"]}


def ols_hac(y, X, lag):
    inv = np.linalg.inv(X.T @ X)
    b = inv @ X.T @ y
    u = X * (y - X @ b)[:, None]
    S = u.T @ u
    for k in range(1, lag + 1):
        G = u[k:].T @ u[:-k]
        S += (1 - k / (lag + 1)) * (G + G.T)
    return b, np.sqrt(np.diag(inv @ S @ inv))


def main() -> None:
    path = md._get(HDI_URL, md.RAW / "undp_hdi.csv")
    hdi = pd.read_csv(path, encoding="latin-1")
    years = [c for c in hdi.columns if c.startswith("hdi_") and c[4:].isdigit()]
    brent = md.fetch_fred("DCOILBRENTEU").resample("YS").mean()
    oil = np.log(brent).diff() * 100
    oil.index = oil.index.year
    rows, out_rows = [], []
    for group, isos in GROUPS.items():
        panel = []
        for iso in isos:
            r = hdi[hdi["iso3"] == iso]
            if r.empty:
                continue
            s = pd.Series(r[years].values[0].astype(float), index=[int(c[4:]) for c in years]).dropna()
            d = pd.DataFrame({"dhdi": s.diff() * 1000, "oil": oil.reindex(s.index), "oil_1": oil.reindex(s.index - 1).values})
            d["iso"] = iso
            panel.append(d.dropna())
        P = pd.concat(panel)
        for label, sample in (("all years", P), ("without 2020-2021", P[~P.index.isin([2020, 2021])])):
            y = sample["dhdi"] - sample.groupby("iso")["dhdi"].transform("mean")  # country fixed effects
            X = np.column_stack([sample[c] - sample.groupby("iso")[c].transform("mean") for c in ("oil", "oil_1")])
            order = np.argsort(sample.index.values, kind="stable")  # sort by year for the HAC lags
            b, se = ols_hac(y.values[order], X[order], 2)
            out_rows.append(f"| {group} | {label} | {sample['iso'].nunique()} | {sample.index.min()}–{sample.index.max()} | "
                            f"{len(sample)} | {b[0]:+.3f} ± {se[0]:.3f} | {b[1]:+.3f} ± {se[1]:.3f} | "
                            f"{10 * (b[0] + b[1]):+.2f} |")
        rows.append((group, P))
    today = datetime.now(UTC).date().isoformat()
    out = [
        "# Oil prices and human development (HDI)",
        "",
        f"_Generated by `experiments/hdi_link.py` on {today}. HDI: UNDP Human Development Report 2023/24 composite "
        f"indices time series ({years[0][4:]}–{years[-1][4:]}). Brent: FRED DCOILBRENTEU, annual average. Nothing here "
        "is synthetic._",
        "",
        "Change in HDI (thousandths of a point a year) on the year's and the previous year's log change in Brent (%), "
        "with country fixed effects; ± is a Newey–West standard error. The last column is the two-year effect of a 10% "
        "oil rise, in thousandths of HDI.",
        "",
        "| Group | Years | Countries | Span | Country-years | Brent, same year | Brent, previous year | 10% oil rise, 2-year effect |",
        "|---|---|---|---|---|---|---|---|",
    ] + out_rows + [
        "",
        "For scale, a typical country's HDI rises by 3 to 8 thousandths a year. HDI is annual and slow-moving, so it "
        "belongs on the product as a long-run context card, not as a monthly link in the what-if chain.",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    print("\n".join(out))


if __name__ == "__main__":
    main()
