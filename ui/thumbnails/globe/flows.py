# python3 flows.py: data.js for the globe stills, from the repo's own tables
#   oil: pre-war kb/d via Hormuz by destination, and each route's last point (ui/industry/index.html, EIA 2024)
#   gas: LNG Mt/yr through Hormuz (ui/app/data/gas.json, experiments/gas_routes.py; figures unverified)
import json, pathlib, re
HERE = pathlib.Path(__file__).parent; REPO = HERE.resolve().parents[2]
src = (REPO / "ui/industry/index.html").read_text()
start = src.index("  const C = {"); block = src[start:src.index("\n  };", start)]
oil = []
for m in re.finditer(r'^\s*"([^"]+)": \{ c: [\d.]+, h: (\d+),.*$', block, re.M):
    h, line = int(m.group(2)), m.group(0)
    pairs = re.findall(r'\[(-?[\d.]+), (-?[\d.]+)\]', line); dot = re.search(r'dot: \[(-?[\d.]+), (-?[\d.]+)\]', line)
    end = [float(pairs[-1][0]), float(pairs[-1][1])] if pairs else [float(dot.group(1)), float(dot.group(2))] if dot else None
    if h > 0 and end: oil.append({"name": m.group(1), "h": h, "end": end})
g = json.loads((REPO / "ui/app/data/gas.json").read_text())
gas = [{"from": f["from"], "to": f["to"], "value": f["value"], "start": f["route"]["path"][0], "end": f["route"]["path"][-1]} for f in g["lng"]]
(HERE / "data.js").write_text("// generated by flows.py\nwindow.FLOWS = " + json.dumps({"oil": oil, "gas": gas}) + ";\n")
print(len(oil), "oil,", len(gas), "gas")
